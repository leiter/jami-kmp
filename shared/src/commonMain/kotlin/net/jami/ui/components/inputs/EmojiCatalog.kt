    /** Every emoji whose name contains [query], across all categories. */
    fun search(query: String): List<Emoji> {
        val needle = query.trim().lowercase()
        if (needle.isEmpty()) return emptyList()
        return categories.flatMap { it.emoji }.filter { it.keywords.contains(needle) }
    }
