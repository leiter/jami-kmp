#!/usr/bin/env python3
"""Regenerates shared/src/commonMain/kotlin/net/jami/ui/components/inputs/EmojiCatalog.kt.

The catalogue is single-codepoint emoji from the standard blocks, with their Unicode names as
search keywords. Skin-tone modifiers and ZWJ sequences are deliberately left out: they
multiply the list several times over for a picker nobody scrolls that far down, and a reaction
is read at 22sp where the variants are indistinguishable.

Run with any Python 3 that has a reasonably current unicodedata; re-run when raising the
Unicode version matters more than the churn.
"""
import pathlib
import unicodedata

CATEGORIES = [
    ("Smileys", [(0x1F600, 0x1F64F), (0x1F910, 0x1F92F), (0x1F970, 0x1F97A), (0x1F9D0, 0x1F9DF)]),
    ("Animals & nature", [(0x1F400, 0x1F43F), (0x1F980, 0x1F9AE), (0x1F330, 0x1F344)]),
    ("Food & drink", [(0x1F345, 0x1F37F), (0x1F950, 0x1F96F)]),
    ("Activities", [(0x1F380, 0x1F3C4), (0x1F3C6, 0x1F3CA), (0x1F947, 0x1F94F)]),
    ("Travel & places", [(0x1F680, 0x1F6A4), (0x1F3E0, 0x1F3F0), (0x1F30D, 0x1F320)]),
    ("Objects", [(0x1F4A1, 0x1F4FF), (0x1F527, 0x1F52F)]),
    ("Symbols", [(0x2764, 0x2764), (0x1F493, 0x1F49F), (0x2705, 0x2705), (0x274C, 0x274C), (0x2B50, 0x2B50)]),
]

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "shared/src/commonMain/kotlin/net/jami/ui/components/inputs/EmojiCatalog.kt"

def entries(ranges):
    seen = set()
    for lo, hi in ranges:
        for cp in range(lo, hi + 1):
            ch = chr(cp)
            try:
                name = unicodedata.name(ch)
            except ValueError:
                continue
            if ch in seen:
                continue
            seen.add(ch)
            keywords = name.lower().replace("-", " ")
            yield ch, keywords

body = []
for title, ranges in CATEGORIES:
    rows = list(entries(ranges))
    body.append(f'        EmojiCategory(\n            title = "{title}",\n            emoji = listOf(\n')
    for ch, kw in rows:
        # Kotlin's \u takes exactly four hex digits, so astral codepoints have to go in as
        # UTF-16 surrogate pairs — \u1F602 does not compile.
        units = ch.encode("utf-16-be")
        escaped = "".join(
            f"\\u{units[i] << 8 | units[i + 1]:04X}" for i in range(0, len(units), 2)
        )
        body.append(f'                Emoji("{escaped}", "{kw}"),\n')
    body.append("            ),\n        ),\n")

